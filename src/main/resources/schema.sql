CREATE TABLE IF NOT EXISTS teams (
    team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number VARCHAR(40) NOT NULL UNIQUE,
    employee_name VARCHAR(150) NOT NULL,
    team_id BIGINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_employee_team FOREIGN KEY (team_id) REFERENCES teams(team_id)
);

CREATE TABLE IF NOT EXISTS attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    attendance_date DATE NOT NULL,
    status CHAR(1) NOT NULL CHECK (status IN ('P', 'A')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_attendance_employee FOREIGN KEY (employee_id) REFERENCES employees(employee_id),
    CONSTRAINT uq_attendance_employee_date UNIQUE (employee_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS parts (
    part_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_number VARCHAR(80) NOT NULL UNIQUE,
    part_name VARCHAR(150),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS marks (
    mark_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mark_name VARCHAR(80) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS shifts (
    shift_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_name VARCHAR(80) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS app_metadata (
    metadata_key VARCHAR(80) PRIMARY KEY,
    metadata_value VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS production_entries (
    production_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_date DATE NOT NULL,
    part_id BIGINT NOT NULL,
    mark_id BIGINT NOT NULL,
    shift_id BIGINT NOT NULL,
    production_quantity INTEGER NOT NULL CHECK (production_quantity >= 0),
    remarks VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_production_part FOREIGN KEY (part_id) REFERENCES parts(part_id),
    CONSTRAINT fk_production_mark FOREIGN KEY (mark_id) REFERENCES marks(mark_id),
    CONSTRAINT fk_production_shift FOREIGN KEY (shift_id) REFERENCES shifts(shift_id)
);

CREATE INDEX IF NOT EXISTS idx_attendance_date ON attendance(attendance_date);
CREATE INDEX IF NOT EXISTS idx_attendance_employee ON attendance(employee_id);
CREATE INDEX IF NOT EXISTS idx_employees_team_active ON employees(team_id, is_active);
CREATE INDEX IF NOT EXISTS idx_production_date ON production_entries(production_date);
CREATE INDEX IF NOT EXISTS idx_production_part ON production_entries(part_id);
CREATE INDEX IF NOT EXISTS idx_production_mark ON production_entries(mark_id);
CREATE INDEX IF NOT EXISTS idx_production_shift ON production_entries(shift_id);
